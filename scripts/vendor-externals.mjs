import { build } from "esbuild";
import {
  cp,
  mkdtemp,
  mkdir,
  readFile,
  readdir,
  rm,
  writeFile,
} from "node:fs/promises";
import { createHash } from "node:crypto";
import { tmpdir } from "node:os";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const packageJson = JSON.parse(
  await readFile(join(repositoryRoot, "package.json"), "utf8"),
);
const isCheck = process.argv.includes("--check");
const committedRoot = join(repositoryRoot, "public/assets/js/externals");
const temporaryRoot = isCheck
  ? await mkdtemp(join(tmpdir(), "mermaid-viewer-externals-"))
  : null;
const outputRoot = temporaryRoot || committedRoot;

const layoutVersions = {
  elk: packageJson.devDependencies["@mermaid-js/layout-elk"],
  tidyTree: packageJson.devDependencies["@mermaid-js/layout-tidy-tree"],
};

const trustedMermaidPackages = Object.entries(packageJson.devDependencies)
  .filter(([name, specification]) => (
    name === "mermaid" || specification.startsWith("npm:mermaid@")
  ))
  .map(([packagePath, specification]) => ({
    packagePath,
    version: packagePath === "mermaid"
      ? specification
      : specification.slice("npm:mermaid@".length),
  }));

for (const [name, version] of [
  ...trustedMermaidPackages.map(({ packagePath, version }) => [packagePath, version]),
  ...Object.entries(layoutVersions),
]) {
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
    throw new Error(`${name} must be pinned to an exact semantic version`);
  }
}

if (new Set(trustedMermaidPackages.map(({ version }) => version)).size
    !== trustedMermaidPackages.length) {
  throw new Error("Trusted Mermaid versions must be unique");
}

await rm(outputRoot, { recursive: true, force: true });
await mkdir(join(outputRoot, "licenses"), { recursive: true });

async function bundleLayout({ packageName, globalProperty, filename }) {
  const outfile = join(outputRoot, filename);

  await build({
    bundle: true,
    format: "iife",
    legalComments: "none",
    minify: true,
    outfile,
    platform: "browser",
    stdin: {
      contents: [
        `import layouts from ${JSON.stringify(packageName)};`,
        "globalThis.mermaidViewerLayouts ||= {};",
        `globalThis.mermaidViewerLayouts[${JSON.stringify(globalProperty)}] = layouts;`,
      ].join("\n"),
      loader: "js",
      resolveDir: repositoryRoot,
    },
  });
}

const elkFilename = `layout-elk-${layoutVersions.elk}.min.js`;
const tidyTreeFilename = `layout-tidy-tree-${layoutVersions.tidyTree}.min.js`;

for (const { packagePath, version } of trustedMermaidPackages) {
  await cp(
    join(repositoryRoot, "node_modules", packagePath, "dist/mermaid.min.js"),
    join(outputRoot, `mermaid-${version}.min.js`),
  );
  await cp(
    join(repositoryRoot, "node_modules", packagePath, "LICENSE"),
    join(outputRoot, "licenses", `mermaid-${version}.LICENSE.txt`),
  );
}

await bundleLayout({
  packageName: "@mermaid-js/layout-elk",
  globalProperty: "elk",
  filename: elkFilename,
});
await bundleLayout({
  packageName: "@mermaid-js/layout-tidy-tree",
  globalProperty: "tidy-tree",
  filename: tidyTreeFilename,
});

for (const [packagePath, filename] of [
  ["@mermaid-js/layout-elk", `layout-elk-${layoutVersions.elk}.LICENSE.txt`],
  [
    "@mermaid-js/layout-tidy-tree",
    `layout-tidy-tree-${layoutVersions.tidyTree}.LICENSE.txt`,
  ],
]) {
  await cp(
    join(repositoryRoot, "node_modules", packagePath, "LICENSE"),
    join(outputRoot, "licenses", filename),
  );
}

async function sha384(filename) {
  const bytes = await readFile(join(outputRoot, filename));
  return `sha384-${createHash("sha384").update(bytes).digest("base64")}`;
}

const artifact = async (filename, packageName, version) => ({
  package: packageName,
  version,
  artifact: `./assets/js/externals/${filename}`,
  digest: await sha384(filename),
});

const manifest = {
  schemaVersion: 1,
  algorithm: "SHA-384",
  versions: Object.fromEntries(await Promise.all(
    trustedMermaidPackages.map(async ({ version }) => [
      version,
      await artifact(`mermaid-${version}.min.js`, "mermaid", version),
    ]),
  )),
  layouts: {
    elk: await artifact(elkFilename, "@mermaid-js/layout-elk", layoutVersions.elk),
    "tidy-tree": await artifact(
      tidyTreeFilename,
      "@mermaid-js/layout-tidy-tree",
      layoutVersions.tidyTree,
    ),
    "cose-bilkent": { builtIn: true },
    dagre: { builtIn: true },
  },
};

await writeFile(
  join(outputRoot, "mermaid-integrity.js"),
  [
    "// Generated by scripts/vendor-externals.mjs. Do not edit by hand.",
    `globalThis.MERMAID_VIEWER_INTEGRITY_MANIFEST = ${JSON.stringify(manifest, null, 2)};`,
    "",
  ].join("\n"),
);

async function listFiles(root, relative = "") {
  const entries = await readdir(join(root, relative), { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const path = join(relative, entry.name);
    if (entry.isDirectory()) {
      files.push(...await listFiles(root, path));
    } else {
      files.push(path);
    }
  }

  return files.sort();
}

if (isCheck) {
  try {
    const generatedFiles = await listFiles(outputRoot);
    const committedFiles = await listFiles(committedRoot);

    if (JSON.stringify(generatedFiles) !== JSON.stringify(committedFiles)) {
      throw new Error("Vendored external file list is out of date");
    }

    for (const filename of generatedFiles) {
      const generated = await readFile(join(outputRoot, filename));
      const committed = await readFile(join(committedRoot, filename));

      if (!generated.equals(committed)) {
        throw new Error(`Vendored external is out of date: ${filename}`);
      }
    }

    console.log(`Verified ${generatedFiles.length} vendored files in ${basename(committedRoot)}`);
  } finally {
    await rm(outputRoot, { recursive: true, force: true });
  }
} else {
  console.log(`Wrote trusted external bundles to ${committedRoot}`);
}
